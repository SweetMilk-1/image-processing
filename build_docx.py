# Сборка краткого отчёта в формате .docx (план 1.8).
from docx import Document
from docx.shared import Inches, Pt
from docx.enum.text import WD_ALIGN_PARAGRAPH
import os

doc = Document()
style = doc.styles["Normal"]
style.font.name = "Calibri"
style.font.size = Pt(11)

R = "results"

def h(text, level=1):
    doc.add_heading(text, level=level)

def p(text):
    doc.add_paragraph(text)

def img(path, width=3.1, caption=None):
    if os.path.exists(path):
        doc.add_picture(path, width=Inches(width))
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
    if caption:
        c = doc.add_paragraph(caption)
        c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        c.runs[0].italic = True
        c.runs[0].font.size = Pt(9)

def table(rows, header=True):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Light Grid Accent 1"
    for i, row in enumerate(rows):
        for j, cell in enumerate(row):
            t.cell(i, j).text = str(cell)

# --- Заголовок ---
ti = doc.add_heading("Лабораторная работа 1. Цифровая фильтрация изображений", 0)
ti.alignment = WD_ALIGN_PARAGRAPH.CENTER

# --- 1. Цель ---
h("1. Цель работы", 1)
p("Практическая реализация и анализ методов цифровой фильтрации изображений: "
  "сглаживающих и повышающих резкость фильтров (таблица 1.1), а также получение "
  "контурных препаратов методами «разность гауссианов» (DoG), детектором границ "
  "Кэнни и оператором Собела для горизонтальных контуров (вариант 1, таблица 1.2). "
  "Программа — консольное приложение на C++ с библиотекой OpenCV.")

# --- 2. Теория ---
h("2. Краткие теоретические сведения", 1)
p("Цифровая фильтрация состоит в том, что значение пикселя модифицируется с учётом "
  "соседних элементов. Операция сводится к дискретной свёртке сигнала с импульсной "
  "реакцией (маской) фильтра. Для двумерного изображения:")
p("b[k,l] = Σ_m Σ_n h[m,n] · a[k−m, l−n],")
p("где a — исходное изображение, h — маска (апертура), b — результат. Размер "
  "апертуры (2N+1)×(2N+1) выбирают нечётным, чтобы у маски был центральный элемент (фокус).")
p("Линейные фильтры сохраняют принцип суперпозиции. К ним относятся усредняющие "
  "фильтры и фильтр Гаусса (ФНЧ, сглаживание, подавление шума). Нелинейные — "
  "медианный фильтр: сортирует значения в окне и берёт медиану, подавляя импульсные "
  "помехи и не размывая перепады. Фильтры верхних частот (апертурная коррекция, "
  "операторы Лапласа и Собела) усиливают перепады яркости — повышают резкость или "
  "выделяют контуры.")
p("Свёртка в сигнальной области эквивалентна перемножению спектров в частотной "
  "(теорема о свёртке): L{x*h} = X(f)·H(f). КИХ-фильтры (трансверсальные) имеют "
  "конечную память и всегда устойчивы; БИХ-фильтры (рекурсивные) — бесконечную память, "
  "экономнее по числу операций, но требуют анализа устойчивости.")

# --- 3. Таблица 1.1 ---
h("3. Исходное изображение и фильтрация (таблица 1.1)", 1)
p("Исходное полутоновое изображение (256×256, USC-SIPI 5.1.11 «самолёт», открытая "
  "база тестовых изображений):")
img(f"{R}/00_original.png")
p("Все фильтры реализованы вручную через свёртку (без cv::GaussianBlur, cv::filter2D). "
  "Границы реплицируются. Использованные маски:")
table([
    ["Фильтр", "Маска (ядро) / нормировка"],
    ["Гаусса 3×3", "[[1,4,1],[4,16,4],[1,4,1]], k = 36"],
    ["Гаусса 5×5", "внешнее произведение [1,4,6,4,1], k = 256"],
    ["Мозаика 3×3", "блоки 3×3, всем пикселям блока среднее по блоку"],
    ["Апертурная коррекция 3×3", "[[-1,-1,-1],[-1,13,-1],[-1,-1,-1]], k=5 (S=20%, X=13)"],
    ["Медианный 3×3", "медиана из 9 значений окна"],
])

p("Фильтр Гаусса 3×3 — лёгкое сглаживание:"); img(f"{R}/01_gauss3.png")
p("Фильтр Гаусса 5×5 — более сильное сглаживание (крупная апертура сильнее размывает "
  "детали и шум):"); img(f"{R}/02_gauss5.png")
p("Фильтр «Мозаика» 3×3 — пикселизация: изображение разбивается на блоки 3×3, всем "
  "элементам блока присваивается среднее по блоку:"); img(f"{R}/03_mosaic3.png")
p("Фильтр апертурной коррекции 3×3 — повышение резкости. Из сигнала фокуса вычитаются "
  "соседние элементы; сумма коэффициентов маски равна X−8 = 5, поэтому ядро сохраняет "
  "постоянную составляющую (DC = 1) и не сдвигает яркость. Защита от переполнения — "
  "насыщение результата в [0, 255]:"); img(f"{R}/04_aperture.png")
p("Медианный фильтр 3×3 — подавление точечных помех с сохранением перепадов:"); img(f"{R}/05_median3.png")

# --- 4. Контуры ---
h("4. Контуры исходного изображения", 1)
p("Разность гауссианов (DoG) — модуль разности откликов фильтров Гаусса 3×3 и 5×5, "
  "умноженный на 7 (с насыщением) для наглядности:"); img(f"{R}/06_dog.png")
p("Детектор границ Кэнни — готовая реализация OpenCV cv::Canny(src, 50, 200) "
  "(сглаживание → градиент → подавление немаксимумов → двойная пороговая фильтрация "
  "→ трассировка):"); img(f"{R}/07_canny.png")
p("Индивидуальный вариант 1 — оператор Собела для горизонтальных контуров. "
  "Горизонтальный контур — перепад вдоль вертикального направления, поэтому "
  "используется маска вертикального градиента (∂/∂y):")
p("Gy = [[-1,-2,-1],[0,0,0],[1,2,1]],   контур = |a * Gy|.")
p("Сумма коэффициентов равна нулю → нулевой отклик на ровных участках. Защита от "
  "переполнения — насыщение модуля отклика в [0, 255]:"); img(f"{R}/08_variant.png")

# --- 5. Выводы ---
h("5. Выводы", 1)
p("• Сглаживание. Фильтр Гаусса 5×5 размывает изображение сильнее, чем 3×3: чем больше "
  "апертура, тем заметнее подавление высокочастотных составляющих. Мозаика 3×3 даёт "
  "эффект пикселизации — структуру можно угадать при сокращении числа независимых значений.")
p("• Повышение резкости. Апертурная коррекция усиливает перепады яркости; применять её "
  "надо осторожно — вместе с контурами усиливается и шум, поэтому глубину S ограничивают "
  "20–30 %. Сохранение DC исключает общее смещение яркости.")
p("• Медианный фильтр подавляет импульсные помехи, не размывая границ (в отличие от "
  "линейного усреднения); мелкие детали меньше маски удаляются.")
p("• Контуры. DoG даёт «толстые» градиентные контуры; детектор Кэнни — тонкие "
  "(1 пиксель) линии с подавлением шума за счёт порогов; оператор Собела (вариант 1) "
  "выделяет преимущественно горизонтальные перепады, оставляя ровные участки чёрными. "
  "Для горизонтальных контуров работает вертикальный градиент (∂/∂y), для вертикальных — "
  "горизонтальный (∂/∂x).")
p("• Все фильтры таблицы 1.1 и контурные операторы таблицы 1.2 (всего 10 вариантов) "
  "реализованы в одной программе; переключение варианта — параметром --variant N.")

out = "Отчет.docx"
